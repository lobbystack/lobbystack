/** The region's flag component once its chunk has loaded, or null for a region the package doesn't draw. */
export function loadFlagComponent(region: string): Promise<FlagComponent> | null {
  const loader = FLAG_COMPONENTS[region as keyof typeof FLAG_COMPONENTS];
  return loader ? loader().then((module) => module.default) : null;
}

/** Whether the package draws a flag for this region, as opposed to a shared currency such as XAF. */
export function hasFlagComponent(region: string): boolean {
  return Object.hasOwn(FLAG_COMPONENTS, region);
}
