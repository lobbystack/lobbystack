import { DEFAULT_LOCALE, SUPPORTED_LOCALES, type SupportedLocale } from "@/lib/locale";

import { translatedBasePaths } from "./i18n/translated-base-paths";

/**
 * The marketing site lives under this internal segment. Visitors never see it:
 * the proxy rewrites requests on a marketing host into it, and the app host
 * answers it with a 404.
 */
export const MARKETING_ROUTE_PREFIX = "/site";

/** English is served unprefixed; the other locales keep their `/{locale}/` prefix. */
export const MARKETING_PREFIXED_LOCALES = SUPPORTED_LOCALES.filter((locale) => locale !== DEFAULT_LOCALE);

const translatedPaths = new Set<string>(translatedBasePaths);

export type MarketingHosts = {
  /** The host canonical URLs use. Alias hosts redirect to it. */
  canonical: string;
  aliases: ReadonlySet<string>;
};

/**
 * Reads `MARKETING_HOSTS`, a comma-separated list of hostnames without ports.
 * The first one is canonical. Returns null when the variable is unset, so
 * deployments that don't serve the marketing site route nothing to it.
 */
export function marketingHosts(env: Readonly<Record<string, string | undefined>> = process.env): MarketingHosts | null {
  const hosts = (env.MARKETING_HOSTS ?? "")
    .split(",")
    .map((host) => host.trim().toLowerCase())
    .filter(Boolean);
  const [canonical, ...aliases] = hosts;
  return canonical ? { canonical, aliases: new Set(aliases) } : null;
}

export function hasFileExtension(pathname: string): boolean {
  const lastSegment = pathname.slice(pathname.lastIndexOf("/") + 1);
  return lastSegment.includes(".");
}

/** Splits a public path into its locale and the path after the locale prefix. */
export function splitMarketingPath(pathname: string): { locale: SupportedLocale; rest: string } {
  for (const locale of MARKETING_PREFIXED_LOCALES) {
    if (pathname === `/${locale}`) return { locale, rest: "" };
    if (pathname.startsWith(`/${locale}/`)) return { locale, rest: pathname.slice(locale.length + 1) };
  }
  return { locale: DEFAULT_LOCALE, rest: pathname };
}

/** Pages end in a slash; files keep their exact path. */
export function canonicalMarketingPathname(pathname: string): string {
  if (pathname === "" || pathname === "/") return "/";
  if (pathname.endsWith("/") || hasFileExtension(pathname)) return pathname;
  return `${pathname}/`;
}

// Generated by route handlers under the marketing segment rather than served
// from public/. Paths are relative to the locale prefix.
const machinePathPatterns: readonly RegExp[] = [
  /^\/robots\.txt$/,
  /^\/llms\.txt$/,
  /^\/feed\.xml$/,
  /^\/schemamap\.xml$/,
  /^\/schema\/[a-z0-9-]+\.json$/,
  /^\/openapi\.json$/,
  /^\/og\/.+\.jpg$/,
  /^\/\.well-known\/.+/,
  /^\/api\/status$/,
];

export type MarketingRoute =
  | { kind: "page"; locale: SupportedLocale; internalPath: string }
  | { kind: "redirect"; location: string }
  | { kind: "asset" };

/**
 * Maps a public path on a marketing host to the internal route that renders it.
 * Paths that match nothing generated are left to public/ as static files.
 */
export function resolveMarketingRoute(pathname: string, indexNowKey?: string): MarketingRoute {
  // Next.js's own files and dev tools (HMR, stack frames) serve every host as they are.
  if (pathname.startsWith("/_next/") || pathname.startsWith("/__nextjs")) return { kind: "asset" };
  const { locale, rest } = splitMarketingPath(pathname);
  const base = `${MARKETING_ROUTE_PREFIX}/${locale}`;

  // The build writes the sitemaps to public/ (scripts/marketing/sitemap.mjs).
  if (locale === DEFAULT_LOCALE && /^\/sitemap-[a-z0-9-]+\.xml$/.test(rest)) {
    return { kind: "page", locale, internalPath: `/marketing-sitemaps${rest}` };
  }
  if (machinePathPatterns.some((pattern) => pattern.test(rest))) {
    return { kind: "page", locale, internalPath: `${base}${rest}` };
  }
  if (indexNowKey && locale === DEFAULT_LOCALE && rest === `/${indexNowKey}.txt`) {
    return { kind: "page", locale, internalPath: `${base}/indexnow-key.txt` };
  }
  // Markdown twins of pages: /pricing.md, /fr/index.md, /blog/<slug>.md.
  if (rest.endsWith(".md")) {
    return { kind: "page", locale, internalPath: `${base}/md${rest.slice(0, -".md".length)}` };
  }
  if (hasFileExtension(rest)) return { kind: "asset" };

  const canonical = canonicalMarketingPathname(pathname);
  if (canonical !== pathname) return { kind: "redirect", location: canonical };

  const pagePath = rest.replace(/\/$/, "");
  return { kind: "page", locale, internalPath: `${base}${pagePath}` };
}

const crawlerPattern = /bot|crawl|spider|slurp|bingpreview|facebookexternalhit|linkedinbot|twitterbot|whatsapp|telegrambot/;

export function isCrawler(userAgent: string | null): boolean {
  return crawlerPattern.test(userAgent?.toLowerCase() ?? "");
}

/**
 * Whether an unprefixed English page should send this visitor to their
 * language. Only pages that exist in every locale qualify, and crawlers always
 * get the page they asked for.
 */
export function isLocaleNegotiablePath(pathname: string): boolean {
  if (splitMarketingPath(pathname).locale !== DEFAULT_LOCALE) return false;
  return translatedPaths.has(canonicalMarketingPathname(pathname));
}

/** The same page in another locale: `/pricing/` in French is `/fr/pricing/`. */
export function localizeMarketingPath(pathname: string, locale: SupportedLocale): string {
  const { rest } = splitMarketingPath(pathname);
  const path = rest === "" ? "/" : rest;
  return locale === DEFAULT_LOCALE ? path : `/${locale}${path}`;
}
